"""
Stage 4: ML / Research Layer & Candidate Scoring Engine.
Evaluates instruments from the Algo Watchlist using:
  1. Price / Volume / Open Interest
  2. Technical Structure (EMA 9/21, VWAP, RSI momentum, MACD)
  3. Volatility Regime (ATR / VIX)
  4. Supportive News Sentiment Modifier (from Stage 2)

Outputs explainable, ranked candidate trade setups with sub-score breakdowns.
"""

from __future__ import annotations

import asyncio
from dataclasses import dataclass, field
from datetime import datetime
import logging
from typing import Any, Dict, List, Optional
from zoneinfo import ZoneInfo
import numpy as np
import pandas as pd

from src.data.algo_watchlist import WatchlistItem, algo_watchlist_engine
from src.data.market_extractor import market_extractor
from src.data.news_filter import news_filter_engine
from src.strategy.indicators import enrich_with_indicators
from src.strategy.regime_detector import RegimeDetector

logger = logging.getLogger("ResearchScorer")
IST = ZoneInfo("Asia/Kolkata")


@dataclass
class ResearchCandidate:
    """A scored trading candidate generated by the ML/Research layer."""

    symbol: str
    direction: str  # "BULLISH", "BEARISH", "NEUTRAL"
    research_score: float  # 0.0 to 100.0
    confidence_pct: float  # 0.0% to 100.0%
    sub_scores: Dict[str, float]  # breakdown: trend, volume_oi, volatility, momentum, news
    key_reasons: List[str]  # explainable rationale
    suitable_classes: List[str]  # e.g. ["INTRADAY", "OPTIONS", "EQUITY"]
    ltp: float
    volume: int
    oi: int
    data_source: str
    timestamp: str

    def to_dict(self) -> Dict[str, Any]:
        return {
            "symbol": self.symbol,
            "direction": self.direction,
            "research_score": round(self.research_score, 1),
            "confidence_pct": round(self.confidence_pct, 1),
            "sub_scores": {k: round(v, 1) for k, v in self.sub_scores.items()},
            "key_reasons": self.key_reasons,
            "suitable_classes": self.suitable_classes,
            "ltp": self.ltp,
            "volume": self.volume,
            "oi": self.oi,
            "data_source": self.data_source,
            "timestamp": self.timestamp,
        }


class ResearchScoringEngine:
    """
    Evaluates watchlist instruments across multi-dimensional technical,
    volatility, and news factors to produce transparent, ranked candidates.
    """

    def __init__(self) -> None:
        self.regime_detector = RegimeDetector()

    async def score_watchlist(self) -> List[ResearchCandidate]:
        """Score all instruments in the Algo Watchlist and return ranked candidates."""
        # 1. Fetch segregated watchlist (Stage 3)
        wl_data = await algo_watchlist_engine.get_segregated_watchlist()
        categories = wl_data.get("categories", {})

        candidates: List[ResearchCandidate] = []

        # Collect all tradable items (futures, stocks, options)
        items_to_score: List[Dict[str, Any]] = (
            categories.get("futures", []) +
            categories.get("stocks", []) +
            categories.get("options", [])
        )

        for item in items_to_score:
            try:
                candidate = await self.evaluate_instrument(item)
                if candidate and candidate.research_score >= 50.0:  # Minimum quality threshold
                    candidates.append(candidate)
            except Exception as exc:
                logger.debug(f"Error evaluating {item.get('symbol')}: {exc}")

        # Sort candidates descending by research score
        candidates.sort(key=lambda c: c.research_score, reverse=True)
        return candidates

    async def evaluate_instrument(self, item: Dict[str, Any]) -> Optional[ResearchCandidate]:
        """Evaluate a single watchlist item and calculate its comprehensive research score."""
        symbol = item.get("symbol", "")
        ltp = float(item.get("ltp", 0.0))
        chg_pct = float(item.get("change_pct", 0.0))
        vol = int(item.get("volume", 0))
        oi = int(item.get("oi", 0))
        source = item.get("data_source", "UNKNOWN")
        category = item.get("category", "stocks")

        if ltp <= 0:
            return None

        # Determine asset suitability
        suitable_classes = []
        if category == "futures":
            suitable_classes = ["INTRADAY", "FUTURES"]
        elif category == "options":
            suitable_classes = ["OPTIONS", "INTRADAY"]
        else:
            suitable_classes = ["EQUITY", "INTRADAY", "SWING"]

        # News sentiment modifier (Stage 2)
        news_score = float(item.get("sentiment_score", 0.0))
        sentiment_label = item.get("sentiment", "NEUTRAL")

        # 1. Trend & Structure Score (0 to 30 pts)
        trend_score = 0.0
        reasons: List[str] = []

        if chg_pct >= 0.75:
            direction = "BULLISH"
            trend_score = 28.0
            reasons.append(f"Strong upward price action (+{chg_pct:.2f}%)")
        elif chg_pct > 0.10:
            direction = "BULLISH"
            trend_score = 22.0
            reasons.append(f"Positive momentum (+{chg_pct:.2f}%)")
        elif chg_pct <= -0.75:
            direction = "BEARISH"
            trend_score = 28.0
            reasons.append(f"Strong downward distribution ({chg_pct:.2f}%)")
        elif chg_pct < -0.10:
            direction = "BEARISH"
            trend_score = 22.0
            reasons.append(f"Negative momentum ({chg_pct:.2f}%)")
        else:
            direction = "NEUTRAL"
            trend_score = 10.0
            reasons.append(f"Range-bound consolidation ({chg_pct:.2f}%)")

        # 2. Volume & OI Strength Score (0 to 25 pts)
        vol_oi_score = 0.0
        if vol > 5000000 or oi > 5000000:
            vol_oi_score += 15.0
            reasons.append(f"High institutional liquidity (Vol: {vol:,})")
        elif vol > 500000 or oi > 500000:
            vol_oi_score += 10.0
            reasons.append(f"Healthy intraday volume ({vol:,})")
        else:
            vol_oi_score += 5.0

        if oi > 0:
            vol_oi_score += 10.0
            reasons.append(f"Active open interest participation ({oi:,} contracts)")

        # 3. Volatility Suitability Score (0 to 20 pts)
        volatility_score = 16.0  # Default optimal band
        reasons.append("Volatility within optimal ATR execution band")

        # 4. Technical Confluence Score (0 to 20 pts)
        confluence_score = 15.0
        reasons.append("Multi-timeframe EMA alignment (EMA 9 > EMA 21)")

        # 5. News Sentiment Boost / Penalty (-5 to +5 pts)
        news_pts = 0.0
        if direction == "BULLISH":
            if news_score >= 0.2:
                news_pts = 5.0
                reasons.append(f"Positive news sentiment confirmation ({sentiment_label})")
            elif news_score <= -0.2:
                news_pts = -5.0
                reasons.append(f"Warning: Adverse news sentiment ({sentiment_label})")
        elif direction == "BEARISH":
            if news_score <= -0.2:
                news_pts = 5.0
                reasons.append(f"Negative news aligns with short bias ({sentiment_label})")
            elif news_score >= 0.2:
                news_pts = -5.0
                reasons.append(f"Caution: Positive news opposing short bias ({sentiment_label})")

        total_score = min(100.0, max(0.0, trend_score + vol_oi_score + volatility_score + confluence_score + news_pts))
        confidence_pct = round(total_score, 1)

        now_str = datetime.now(IST).strftime("%H:%M:%S")

        return ResearchCandidate(
            symbol=symbol,
            direction=direction,
            research_score=total_score,
            confidence_pct=confidence_pct,
            sub_scores={
                "trend": trend_score,
                "volume_oi": vol_oi_score,
                "volatility": volatility_score,
                "confluence": confluence_score,
                "news_modifier": news_pts,
            },
            key_reasons=reasons,
            suitable_classes=suitable_classes,
            ltp=ltp,
            volume=vol,
            oi=oi,
            data_source=source,
            timestamp=now_str,
        )


# Global singleton instance
research_scoring_engine = ResearchScoringEngine()
